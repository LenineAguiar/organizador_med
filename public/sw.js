// Armazena os arquivos da interface para acelerar acessos posteriores sem guardar dados médicos.
const CACHE_NAME = "organizador-medico-shell-v1";
const APP_SHELL = ["/", "/manifest.webmanifest", "/icon.svg"];

// Instala o cache básico e ativa a versão atual do service worker.
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)));
  self.skipWaiting();
});

// Remove caches antigos para evitar servir versões incompatíveis da interface.
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))),
    ),
  );
  self.clients.claim();
});

// Usa cache apenas para arquivos da interface; a API e os documentos sempre vêm do servidor.
self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);

  if (request.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/")) {
    return;
  }

  event.respondWith(
    fetch(request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      })
      .catch(() => caches.match(request).then((cached) => cached || caches.match("/"))),
  );
});
